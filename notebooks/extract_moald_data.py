def build_paddy():
    rows = []
    for row in PADDY:
        d = row[0]
        ea, ep, ey = row[1], row[2], row[3]
        ma, mp, my = row[4], row[5], row[6]
        if ea and ea > 0:
            rows.append(dict(district=d, crop_name="Paddy",
                             season="Chaite (Early)",
                             area_ha=ea, production_mt=ep, yield_mt_ha=ey))
        if ma and ma > 0:
            rows.append(dict(district=d, crop_name="Paddy",
                             season="Barkhe (Main)",
                             area_ha=ma, production_mt=mp, yield_mt_ha=my))
    return pd.DataFrame(rows)


def build_multi(data, crops):
    """Build DataFrame for tables with multiple crops per row."""
    rows = []
    n = len(crops)
    for row in data:
        d = row[0]
        for i, crop in enumerate(crops):
            base = 1 + i * 3
            a, p, y = row[base], row[base+1], row[base+2]
            if a and a > 0:
                rows.append(dict(district=d, crop_name=crop,
                                 season="Annual",
                                 area_ha=a, production_mt=p, yield_mt_ha=y))
    return pd.DataFrame(rows)


