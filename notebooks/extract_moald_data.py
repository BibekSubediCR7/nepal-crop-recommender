def main():
    print("=" * 55)
    print("  MoALD Crop Data Builder — Nepal Crop Recommender")
    print("=" * 55)

    df_paddy  = build_paddy()
    df_mw     = build_multi(MAIZE_WHEAT,
                            ["Maize", "Wheat"])
    df_mbb    = build_multi(MILLET_BUCKWHEAT_BARLEY,
                            ["Millet", "Buckwheat", "Barley"])
    df_cash   = build_cash_crops()
    df_pulses = build_pulses()

    for name, df in [("Paddy", df_paddy), ("Maize/Wheat", df_mw),
                     ("Millet/Buckwheat/Barley", df_mbb),
                     ("Cash Crops", df_cash), ("Pulses", df_pulses)]:
        print(f"  {name:30s}: {len(df):4d} rows")

    # ── Combine ───────────────────────────────────────────────────────────────
    combined = pd.concat(
        [df_paddy, df_mw, df_mbb, df_cash, df_pulses],
        ignore_index=True
    )
    combined["district"] = combined["district"].str.strip().str.title()
    combined = combined.sort_values(
        ["district", "crop_name", "season"]
    ).reset_index(drop=True)

    print(f"\n  Total rows  : {len(combined)}")
    print(f"  Crops       : {sorted(combined['crop_name'].unique())}")
    print(f"  Districts   : {combined['district'].nunique()}")

    # ── 1. Full table ─────────────────────────────────────────────────────────
    p1 = os.path.join(PROCESSED_DIR, "moald_crops_full.csv")
    combined.to_csv(p1, index=False)
    print(f"\n  ✅ moald_crops_full.csv           → {p1}")

    # ── 2. Yield reference for Streamlit ──────────────────────────────────────
    ref = (
        combined.groupby(["district", "crop_name"], as_index=False)
        .agg(avg_yield_mt_ha=("yield_mt_ha", "mean"),
             avg_production_mt=("production_mt", "mean"))
        .round(2)
    )
    p2 = os.path.join(PROCESSED_DIR, "crop_yield_reference.csv")
    ref.to_csv(p2, index=False)
    print(f"  ✅ crop_yield_reference.csv        → {p2}")

    # ── 3. Model-ready file (no yield/production) ─────────────────────────────
    model = combined[["district", "crop_name", "season", "area_ha"]].copy()
    p3 = os.path.join(PROCESSED_DIR, "moald_crops_for_model.csv")
    model.to_csv(p3, index=False)
    print(f"  ✅ moald_crops_for_model.csv       → {p3}")

    print(f"\n{'=' * 55}")
    print("  Done! Next: clean rainfall, temperature, soil data")
    print("  then merge everything into nepal_crop_final.csv")
    print(f"{'=' * 55}")


if __name__ == "__main__":
    main()